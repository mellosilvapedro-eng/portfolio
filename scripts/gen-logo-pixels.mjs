/* ────────────────────────────────────────────────────────────────────────
   Turns public/logo.svg into the row strings in lib/logo-pixels.ts.

   The mark is already a pixel grid — 315 flat-grey <rect>s on a 20×20 lattice,
   clipped to a circle — so it doesn't need to be redrawn to animate cell by
   cell. It only needs to be read back out of the file it already lives in.

   Run after editing the logo:  node scripts/gen-logo-pixels.mjs
   ──────────────────────────────────────────────────────────────────────── */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const ALPHABET =
  "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
const EMPTY = ".";
const GRID = 20;
const ORIGIN = 2;
const PITCH = 3;
const CELL = 2.5;

const svg = readFileSync(join(root, "public/logo.svg"), "utf8");

/* Only the lattice cells — the two full-bleed rects (the rounded plate and the
   #161616 backing) are the wrong size and get skipped by the CELL check. */
const pattern =
  /<rect x="([\d.]+)" y="([\d.]+)" width="([\d.]+)" height="([\d.]+)" fill="#([0-9a-f]{6})"\s*\/>/g;

const rows = Array.from({ length: GRID }, () => Array(GRID).fill(EMPTY));
let found = 0;

for (const [, x, y, w, h, hex] of svg.matchAll(pattern)) {
  if (Number(w) !== CELL || Number(h) !== CELL) continue;

  const col = (Number(x) - ORIGIN) / PITCH;
  const row = (Number(y) - ORIGIN) / PITCH;
  if (!Number.isInteger(col) || !Number.isInteger(row)) {
    throw new Error(`cell at ${x},${y} is off the ${PITCH}px lattice`);
  }

  /* The renderer draws the mark as one ink at varying opacity, which only
     holds if every cell is neutral. It is, by construction — but assert it,
     because a colour slipping into the logo would silently lose its hue. */
  const [r, g, b] = [hex.slice(0, 2), hex.slice(2, 4), hex.slice(4, 6)];
  if (r !== g || g !== b) throw new Error(`cell #${hex} is not neutral`);

  const grey = parseInt(r, 16);

  /* Quantised to 64 levels — a 4/255 step, invisible at any size the mark is
     ever drawn, and it buys a grid you can read as a picture in the source. */
  rows[row][col] = ALPHABET[Math.round(grey / 4)];
  found += 1;
}

if (found === 0) throw new Error("no lattice cells matched — did logo.svg change shape?");

const body = rows.map((row) => `  "${row.join("")}",`).join("\n");

writeFileSync(
  join(root, "lib/logo-pixels.ts"),
  `/* ────────────────────────────────────────────────────────────────────────
   The mark, as data — generated by scripts/gen-logo-pixels.mjs from
   public/logo.svg. Don't hand-edit; edit the logo and re-run the script.

   The mark is a dithered disc on a 20×20 lattice: ${found} cells of flat grey,
   3px apart, 2.5px each, inside a 64-unit box. Kept as data rather than as an
   <img> so the splash can animate cells individually — see
   components/logo-mark.
   ──────────────────────────────────────────────────────────────────────── */

/** Cells per side. */
export const GRID = ${GRID};
/** Both axes of the source viewBox. */
export const VIEWBOX = 64;
/** Where the first cell starts, in viewBox units. */
export const ORIGIN = ${ORIGIN};
/** Centre-to-centre spacing, in viewBox units. */
export const PITCH = ${PITCH};
/** One cell's side, in viewBox units — a hair under the pitch, so the lattice
    keeps its 0.5 gap and the disc reads as pixels rather than as a fill. */
export const CELL = ${CELL};

/** Level alphabet: index × 4 is the cell's grey, 0–252. */
const LEVELS =
  "${ALPHABET}";

/* One string per row, one character per cell — "." for the cells the circle
   clips away. The disc is legible here as its own silhouette, which is the
   point: this stays reviewable in a diff. */
const ROWS = [
${body}
];

export type LogoCell = {
  /** Left edge, in viewBox units. */
  x: number;
  /** Top edge, in viewBox units. */
  y: number;
  /** The cell's grey, as ink opacity — see components/logo-mark for why the
      mark is drawn as one ink at varying opacity rather than as 77 greys. */
  opacity: number;
  /** Lattice position, for anything deriving motion from where a cell sits. */
  col: number;
  row: number;
};

/** Decoded once at module load. Server-only in practice: the splash that reads
    this renders on the server and ships as markup, not as data. */
export const LOGO_CELLS: readonly LogoCell[] = ROWS.flatMap((line, row) =>
  [...line].flatMap((char, col) => {
    const level = LEVELS.indexOf(char);
    if (level < 0) return [];
    return [
      {
        x: ORIGIN + col * PITCH,
        y: ORIGIN + row * PITCH,
        opacity: Number(((level * 4) / 255).toFixed(3)),
        col,
        row,
      },
    ];
  }),
);
`,
);

console.log(`lib/logo-pixels.ts — ${found} cells`);
